#!/usr/bin/env python3
"""Generate knowledge/mitre/capec.yaml from MITRE's CAPEC STIX bundle.

    curl -sLo stix-capec.json \
      https://raw.githubusercontent.com/mitre/cti/master/capec/2.1/stix-capec.json
    python3 scripts/gen_capec.py stix-capec.json > knowledge/mitre/capec.yaml

CAPEC is the layer between a weakness (CWE) and a technique (ATT&CK): each
attack pattern lists the CWEs it exploits, its prerequisites, the skills it
needs, an execution flow (Explore -> Experiment -> Exploit, with techniques per
step) and, for many, the ATT&CK techniques it maps to. Loaded into the RAG
corpus by etl/load_knowledge_documents.py (`_render_capec`) so the PoC
pipeline can retrieve "how is this weakness attacked, step by step".

Deterministic: output is sorted by CAPEC id, so a regeneration diff shows only
real upstream changes. Deprecated and revoked patterns are dropped.
"""
from __future__ import annotations

import html
import json
import re
import sys

import yaml

NOTICE = ("CAPEC(TM) content (c) The MITRE Corporation, reproduced under the CAPEC "
          "Terms of Use (https://capec.mitre.org/about/termsofuse.html).")


def _text(s) -> str:
    """HTML fragment -> one line of plain text."""
    s = re.sub(r"<[^>]+>", " ", str(s or ""))
    return re.sub(r"\s+", " ", html.unescape(s)).strip()


def parse_execution_flow(raw: str) -> list:
    """[{phase, step, detail, techniques[]}] from CAPEC's execution-flow HTML."""
    out = []
    if not raw:
        return out
    for pm in re.finditer(r"<h3>\s*([^<]+?)\s*</h3>(.*?)(?=<h3>|\Z)", raw, re.S):
        phase = _text(pm.group(1))
        # CAPEC renders each step as <li>...</li> followed by ITS OWN technique
        # table, so pair every step with the table directly after it.
        for li in re.finditer(r"<li>(.*?)</li>\s*(<table>.*?</table>)?", pm.group(2), re.S):
            body = li.group(1)
            title = _text((re.search(r"<b>(.*?)</b>", body, re.S) or [None, ""])[1]).rstrip(":")
            para = _text((re.search(r"<p>(.*?)</p>", body, re.S) or [None, body])[1])
            detail = para[len(title):].lstrip(": ").strip() if title and para.startswith(title) else para
            techs = [_text(t) for t in re.findall(r"<td>(.*?)</td>", li.group(2) or "", re.S)]
            out.append({"phase": phase, "step": title or detail[:80], "detail": detail[:600],
                        "techniques": [t[:300] for t in techs[:8]]})
    return out


def build(bundle: dict) -> dict:
    objs = bundle.get("objects") or []
    by_ref = {o["id"]: o for o in objs if o.get("type") == "attack-pattern"}

    def cid(o):
        return next((r["external_id"] for r in o.get("external_references") or []
                     if r.get("source_name") == "capec"), None)

    patterns, version = [], None
    for o in objs:
        if (o.get("type") != "attack-pattern" or o.get("revoked")
                or o.get("x_capec_status") == "Deprecated" or not cid(o)):
            continue
        version = version or o.get("x_capec_version")
        refs = o.get("external_references") or []
        patterns.append({
            "id": cid(o),
            "name": o.get("name"),
            "abstraction": o.get("x_capec_abstraction"),
            "likelihood": o.get("x_capec_likelihood_of_attack"),
            "severity": o.get("x_capec_typical_severity"),
            "description": _text(o.get("description"))[:1500],
            "prerequisites": [_text(p)[:400] for p in (o.get("x_capec_prerequisites") or [])],
            "skills": [f"{k}: {_text(v)[:200]}" for k, v in
                       (o.get("x_capec_skills_required") or {}).items()],
            "cwes": sorted({r["external_id"] for r in refs
                            if r.get("source_name") == "cwe" and r.get("external_id")}),
            "attack": sorted({"T" + str(r["external_id"]).lstrip("T") for r in refs
                              if r.get("source_name") == "ATTACK" and r.get("external_id")}),
            "parents": sorted(filter(None, (cid(by_ref[r]) for r in
                                            (o.get("x_capec_child_of_refs") or [])
                                            if r in by_ref))),
            "execution_flow": parse_execution_flow(o.get("x_capec_execution_flow") or ""),
        })
    patterns.sort(key=lambda p: int(p["id"].split("-")[1]))
    return {"source": "MITRE CAPEC STIX 2.1 (mitre/cti capec/2.1/stix-capec.json)",
            "capec_version": version, "notice": NOTICE, "patterns": patterns}


def main(argv=None):
    argv = argv or sys.argv[1:]
    if not argv:
        sys.exit(__doc__)
    with open(argv[0], encoding="utf-8") as f:
        data = build(json.load(f))
    sys.stdout.write("# GENERATED by scripts/gen_capec.py -- do not hand-edit.\n")
    sys.stdout.write(yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100))


if __name__ == "__main__":
    main()
