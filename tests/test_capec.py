"""CAPEC attack patterns: generated correctly, embedded in RAG, used by the PoC
pipeline.

Run standalone:  pytest tests/test_capec.py -q

CAPEC is the layer between a weakness (CWE) and a technique (ATT&CK): which
attack patterns exploit a CWE, what they need, and the Explore -> Experiment ->
Exploit steps. knowledge/mitre/capec.yaml is generated by scripts/gen_capec.py
from MITRE's STIX bundle; etl/load_knowledge_documents.py embeds one document
per pattern (operator ask: "ensure it is in the rag"); etl/capec.py answers the
exact lookups for the class hints block and the build preview.
The execution-flow fixture is CAPEC-66's real HTML from the STIX bundle.
"""
import importlib.util
import pathlib

import pytest

REPO = pathlib.Path(__file__).resolve().parents[1]
CAPEC_YAML = REPO / "knowledge" / "mitre" / "capec.yaml"
FIXTURE = REPO / "tests" / "fixtures" / "capec66_execution_flow.html"


def _gen():
    spec = importlib.util.spec_from_file_location("gen_capec", REPO / "scripts" / "gen_capec.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def _data():
    yaml = pytest.importorskip("yaml")
    return yaml.safe_load(CAPEC_YAML.read_text(encoding="utf-8"))


def test_execution_flow_pairs_each_step_with_its_own_techniques():
    pytest.importorskip("yaml")
    flow = _gen().parse_execution_flow(FIXTURE.read_text(encoding="utf-8"))
    assert [s["phase"] for s in flow] == ["Explore", "Experiment", "Experiment", "Exploit"]
    first_exp = flow[1]
    assert first_exp["step"].startswith("Determine user-controllable input")
    assert first_exp["techniques"], (
        "the first Experiment step lost its techniques -- they were attached "
        "to the phase's last step instead")
    assert all("<" not in s["detail"] for s in flow), "HTML leaked into a step"


def test_the_generated_file_is_complete_and_well_formed():
    d = _data()
    pats = d["patterns"]
    assert d["capec_version"] and d["notice"]
    assert len(pats) > 500, "CAPEC has ~560 active patterns; got %d" % len(pats)
    ids = [p["id"] for p in pats]
    assert len(ids) == len(set(ids)) and ids == sorted(ids, key=lambda x: int(x.split("-")[1]))
    import re
    for p in pats:
        assert all(re.fullmatch(r"CWE-\d+", c) for c in p["cwes"]), p["id"]
        assert all(re.fullmatch(r"T\d{4}(\.\d{3})?", t) for t in p["attack"]), p["id"]
    sqli = next(p for p in pats if p["id"] == "CAPEC-66")
    assert "CWE-89" in sqli["cwes"] and sqli["execution_flow"]


def test_capec_is_embedded_and_class_tagged():
    """The point of the change: CAPEC must reach rag_documents, and a build
    that holds a class must be able to ask for its patterns."""
    pytest.importorskip("httpx")
    from etl import load_knowledge_documents as lk
    docs = lk.render_file("mitre/capec.yaml", _data())
    assert len(docs) > 500
    by = {d[2]["capec"]: d for d in docs}
    assert by["CAPEC-66"][2]["vuln_class"] == "sqli" and by["CAPEC-66"][2]["doc_type"] == "capec"
    assert "Prerequisites:" in by["CAPEC-66"][1] and "[Exploit]" in by["CAPEC-66"][1]
    assert sum(1 for d in docs if d[2]["vuln_class"]) > 50
    assert lk.render_file("mitre/attack_map.yaml", {"techniques": {}}) == [], (
        "attack_map.yaml is declared RAG_LOAD_DEBT; the mitre renderer must not "
        "silently claim to embed it")


def test_accessor_ranks_concrete_patterns_for_a_class():
    from etl import capec
    pats = capec.for_class("sqli")
    assert pats and all("CWE-89" in p["cwes"] or "CWE-1286" in p["cwes"] or p["cwes"] for p in pats)
    assert pats[0]["abstraction"] != "Meta", "an umbrella pattern outranked a concrete one"
    assert capec.for_class("no-such-class") == []
    assert "Needs:" in capec.brief(capec.get("CAPEC-66"))


def test_class_hints_block_carries_capec():
    """Every craft prompt and the description-read step get the class's top
    CAPEC patterns through _class_reading_hints_block (executed here)."""
    import ast
    api = REPO / "app" / "rag-api" / "api.py"
    fn = next(n for n in ast.parse(api.read_text(encoding="utf-8")).body
              if isinstance(n, ast.FunctionDef) and n.name == "_class_reading_hints_block")
    from etl import vuln_classes
    ns = {"_vc": lambda: vuln_classes}
    exec(compile(ast.Module([fn], []), "api.py", "exec"), ns)
    blk = ns["_class_reading_hints_block"]("sqli")
    assert "CAPEC CAPEC-" in blk and "Steps:" in blk
